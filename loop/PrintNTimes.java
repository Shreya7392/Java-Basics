package loop;
import java.util.*;
public class PrintNTimes {
    public static void main(String[] args) {
         Scanner sc = new Scanner(System.in);
        System.out.println("Enter the numbers of n times you want to print:");
        int n = sc.nextInt();
        for (int i = 0; i < n; i++){
            System.out.println("***");
            System.out.println("******");

        }
    }
    
}
